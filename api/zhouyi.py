def gua_text(name):
    """按卦名取卦辞 / 大象 / 爻辞。未收录返回 None。"""
    d = GUA_TEXT.get(name)
    if not d:
        return None
    return {
        'name': name,
        'ci': d['ci'],
        'xiang': d['xiang'],
        'note': d.get('note', ''),
        'yong': d.get('yong', ''),
        'yao': [{'pos': i, 'pos_name': _YAO_NAMES[i], 'text': t}
                for i, t in enumerate(d['yao'])],
    }


def self_check():
    """完整性自检：应恰好 64 卦、每卦 6 条爻辞。返回问题列表（空为通过）。"""
    problems = []
    if len(GUA_TEXT) != 64:
        problems.append('卦数 = %d，应为 64' % len(GUA_TEXT))
    for k, v in GUA_TEXT.items():
        if len(v.get('yao', [])) != 6:
            problems.append('%s 爻辞 %d 条' % (k, len(v.get('yao', []))))
        for key in ('ci', 'xiang'):
            if not v.get(key):
                problems.append('%s 缺 %s' % (k, key))
    return problems


if __name__ == '__main__':
    ps = self_check()
    print('卦数：%d' % len(GUA_TEXT))
    print('自检：%s' % ('通过' if not ps else '；'.join(ps)))
