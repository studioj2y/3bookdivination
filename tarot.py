def draw(spread_key, allow_reversed=True, rng_seed=None):
    """按指定牌阵抽牌，返回结构化结果。"""
    if spread_key not in SPREADS:
        raise ValueError(f"未知牌阵: {spread_key}，可用: {list(SPREADS.keys())}")
    spread = SPREADS[spread_key]
    n = spread["size"]

    if rng_seed is not None:
        random.seed(rng_seed)

    # 不放回抽 n 张
    pool = DECK[:]
    chosen = random.sample(pool, n)
    positions = spread["positions"]

    result = []
    for i, card in enumerate(chosen):
        reversed_flag = allow_reversed and (random.random() < 0.5)
        meaning = card["rev"] if reversed_flag else card["up"]
        result.append({
            "position": positions[i],
            "card": card,
            "reversed": reversed_flag,
            "meaning": meaning,
        })
    return {
        "spread_key": spread_key,
        "spread_name": spread["name"],
        "spread_desc": spread["desc"],
        "cards": result,
    }


