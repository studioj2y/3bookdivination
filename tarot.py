def _rws_filename(card):
    if card["arcana"] == "major":
        num = int(card["key"][1:])
        return f"Pictorial Key to the Tarot {num:02d} {card['name_en']}.jpg"
    suit_full = {"W": "Wands", "C": "Cups", "S": "Swords", "P": "Pentacles"}[card["key"][0]]
    rank_map = {"Ace": "01", "2": "02", "3": "03", "4": "04", "5": "05", "6": "06",
                "7": "07", "8": "08", "9": "09", "10": "10",
                "Page": "11", "Knight": "12", "Queen": "13", "King": "14"}
    nn = rank_map[card["rank"]]
    return f"Pictorial Key to the Tarot {suit_full} {nn}.jpg"


def _img_url(card):
    return ("https://commons.wikimedia.org/wiki/Special:FilePath/"
            + quote(_rws_filename(card)) + "?width=300")


def build_deck():
    """构建完整的 78 张牌。"""
    deck = []
    for c in MAJOR_ARCANA:
        card = {
            "key": f"M{c['num']:02d}",
            "arcana": "major",
            "name_en": c["en"],
            "name_cn": c["cn"],
            "up": c["up"],
            "rev": c["rev"],
        }
        _enrich(card, None)
        deck.append(card)
    for suit_en, suit_cn in SUITS.items():
        for rank, (up, rev) in MINOR_PROFILES[suit_en].items():
            key = f"{suit_en[0]}{rank}"
            # 数字牌 rank 为字符串数字；宫廷牌为英文
            if rank == "Ace":
                label = f"{suit_cn}ACE"
            elif rank in ("Page", "Knight", "Queen", "King"):
                court = {"Page": "侍从", "Knight": "骑士", "Queen": "王后", "King": "国王"}[rank]
                label = f"{suit_cn}{court}"
            else:
                label = f"{suit_cn}{rank}"
            card = {
                "key": key,
                "arcana": "minor",
                "suit": suit_en,
                "name_en": f"{rank} of {suit_en}",
                "name_cn": label,
                "up": up,
                "rev": rev,
            }
            _enrich(card, rank)
            deck.append(card)
    return deck


def _enrich(card, rank):
    """为每张牌补充 图片路径 与 扩充释义（正/逆位各 2~3 行）。"""
    card["rank"] = rank
    # 本地打包的图片：由本服务 /tarot_images/<key>.jpg 提供（离线可用）
    card["img"] = f"/tarot_images/{card['key']}.jpg"
    # 远程兜底（联网时可用，发布到无静态服务的环境时可用作回退）
    card["img_remote"] = _img_url(card)
    ul, rl = LONG.get(card["key"], (card["up"], card["rev"]))
    card["up_long"] = ul
    card["rev_long"] = rl


